"""Shared transforms and safe checkpoint helpers."""
import json
from pathlib import Path
import torch
from torchvision import transforms


def build_transforms(image_size: int = 224, train: bool = False):
    if image_size < 32:
        raise ValueError("image_size must be at least 32")
    ops = [transforms.Resize((image_size, image_size))]
    if train:
        # Review augmentation for the target modality and clinical task.
        ops += [
            transforms.RandomRotation(degrees=7),
            transforms.RandomAffine(degrees=0, translate=(0.03, 0.03)),
        ]
    ops += [
        transforms.ToTensor(),
        transforms.Normalize(mean=(0.485, 0.456, 0.406),
                             std=(0.229, 0.224, 0.225)),
    ]
    return transforms.Compose(ops)


def save_classes(classes: list[str], path: str | Path) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(classes, indent=2), encoding="utf-8")


def load_checkpoint(path: str | Path, device: torch.device):
    # Only load checkpoints generated by this project's own training script.
    return torch.load(path, map_location=device, weights_only=True)
